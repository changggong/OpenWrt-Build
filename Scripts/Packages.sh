#安装和更新软件包
UPDATE_PACKAGE() {
	local PKG_NAME=$1
	local PKG_REPO=$2
	local PKG_BRANCH=$3
	local PKG_SPECIAL=$4
	local PKG_LIST=("$PKG_NAME" $5)  # 第5个参数为自定义名称列表
	local REPO_NAME=${PKG_REPO#*/}
	local REPO_PATH="./package/$REPO_NAME"

	echo " "

	# 删除本地可能存在的不同名称的软件包
	for NAME in "${PKG_LIST[@]}"; do
		# 查找匹配的目录
		echo "Search directory: $NAME"
		local FOUND_DIRS=$(find ./feeds/luci/ ./feeds/packages/ -maxdepth 3 -type d -iname "*$NAME*" 2>/dev/null)

		# 删除找到的目录
		if [ -n "$FOUND_DIRS" ]; then
			while read -r DIR; do
				rm -rf "$DIR"
				echo "Delete directory: $DIR"
			done <<< "$FOUND_DIRS"
		else
			echo "Not fonud directory: $NAME"
		fi
	done

	# 克隆 GitHub 仓库
	# 克隆失败必须直接终止，否则后续 make defconfig 会静默丢掉这个插件，
	# 编出一个“看起来成功”但缺功能的固件。
	if ! git clone --depth=1 --single-branch --branch "$PKG_BRANCH" "https://github.com/$PKG_REPO.git" "$REPO_PATH"; then
		echo "ERROR: clone failed: $PKG_REPO ($PKG_BRANCH)"
		exit 1
	fi

	# 处理克隆的仓库
	if [[ "$PKG_SPECIAL" == "pkg" ]]; then
		# 上游一旦改名子包目录，find 会一个都匹配不到，然后 rm -rf 把整个克隆删掉，
		# 插件静默消失。所以先确认确实匹配到了，再复制。
		local PKG_MATCHES
		PKG_MATCHES=$(find "$REPO_PATH"/*/ -maxdepth 3 -type d -iname "*$PKG_NAME*" -prune 2>/dev/null)
		if [ -z "$PKG_MATCHES" ]; then
			echo "ERROR: $PKG_REPO 里找不到匹配 '$PKG_NAME' 的子包，仓库结构可能已变化"
			exit 1
		fi
		while IFS= read -r DIR; do
			cp -rf "$DIR" ./package
		done <<< "$PKG_MATCHES"
		rm -rf "$REPO_PATH"
	fi
}

